"""Render a target-independent GitHub Actions regression workflow."""

from __future__ import annotations

import re
import shlex
import unicodedata
from pathlib import Path, PurePosixPath

from api_test_pilot.configuration import ProjectConfiguration

_GITHUB_ENVIRONMENT_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
_GITHUB_EXPRESSION_CHARACTERS = frozenset("${}")


def _workflow_path(value: str | Path, *, field: str) -> str:
    """Validate and normalize a project-relative POSIX path before YAML interpolation."""
    raw = value.as_posix() if isinstance(value, Path) else value
    if not raw or any(unicodedata.category(character).startswith("C") for character in raw):
        raise ValueError(f"{field} must not be empty or contain control characters")
    if "\\" in raw:
        raise ValueError(f"{field} must use POSIX path separators")
    if "'" in raw or any(character in _GITHUB_EXPRESSION_CHARACTERS for character in raw):
        raise ValueError(f"{field} contains unsafe YAML or GitHub expression characters")
    path = PurePosixPath(raw)
    if path.is_absolute():
        raise ValueError(f"{field} must be relative to the project")
    if ".." in path.parts:
        raise ValueError(f"{field} must not traverse outside the project")
    if str(path) == "." or path.parts[0].startswith("-"):
        raise ValueError(f"{field} must identify a project file or directory")
    return path.as_posix()


def _secret_environment(configuration: ProjectConfiguration) -> str:
    """Render explicit Actions secret bindings for discovered auth schemes."""
    if not configuration.authentication:
        return ""
    environments = sorted(set(configuration.authentication.values()))
    invalid = [
        environment
        for environment in environments
        if not _GITHUB_ENVIRONMENT_NAME.fullmatch(environment)
    ]
    if invalid:
        rendered = ", ".join(repr(environment) for environment in invalid)
        raise ValueError(f"Authentication environment names must be valid identifiers: {rendered}")
    lines = [
        f"          {environment}: ${{{{ secrets.{environment} }}}}" for environment in environments
    ]
    return "\n".join(lines)


def render_workflow(
    configuration: ProjectConfiguration,
    *,
    config_path: Path,
) -> str:
    """Render Actions YAML that consumes the same configuration as local commands."""
    workflow_config = _workflow_path(config_path, field="config_path")
    workflow_suite = _workflow_path(configuration.artifacts.suite, field="artifacts.suite")
    workflow_reports = _workflow_path(configuration.artifacts.reports, field="artifacts.reports")
    report_path = f"{workflow_reports}/report.json"
    downloaded_report = f"deterministic-artifacts/{report_path}"
    quoted_config = shlex.quote(workflow_config)
    quoted_report = shlex.quote(report_path)
    quoted_downloaded_report = shlex.quote(downloaded_report)
    auth_environment = _secret_environment(configuration)
    regression_environment = f"        env:\n{auth_environment}\n" if auth_environment else ""
    return f"""# Generated by API Test Pilot; edit the project configuration to change targets.
name: API regression

on:
  pull_request:
  push:
    branches: [main]
  workflow_dispatch:
    inputs:
      analyze_failures:
        description: Send failed response excerpts to GitHub Copilot
        required: false
        type: boolean
        default: false
  schedule:
    - cron: "17 5 * * 1"

permissions:
  contents: read

concurrency:
  group: api-regression-${{{{ github.ref }}}}
  cancel-in-progress: true

jobs:
  regression:
    name: Contract regression
    runs-on: ubuntu-latest
    steps:
      - name: Check out source
        uses: actions/checkout@v7
      - name: Install uv
        uses: astral-sh/setup-uv@v9.0.0
        with:
          enable-cache: true
      - name: Install Python and locked dependencies
        run: |
          uv python install 3.12
          uv sync --all-extras --locked --no-editable
      - name: Generate scenarios from project configuration
        run: >-
          uv run --no-sync api-test-pilot generate --config {quoted_config}
      - name: Execute regression
        id: regression
        continue-on-error: true
{regression_environment}        run: >-
          uv run --no-sync api-test-pilot run --config {quoted_config}
      - name: Upload generated scenarios and reports
        if: always()
        uses: actions/upload-artifact@v7
        with:
          name: api-regression-report
          path: |
            {workflow_suite}
            {workflow_reports}/
          if-no-files-found: error
      - name: Notify configured Slack or email channels
        if: always() && hashFiles('{report_path}') != ''
        env:
          SLACK_WEBHOOK_URL: ${{{{ secrets.SLACK_WEBHOOK_URL }}}}
          SMTP_HOST: ${{{{ secrets.SMTP_HOST }}}}
          SMTP_PORT: ${{{{ secrets.SMTP_PORT }}}}
          SMTP_USERNAME: ${{{{ secrets.SMTP_USERNAME }}}}
          SMTP_PASSWORD: ${{{{ secrets.SMTP_PASSWORD }}}}
          EMAIL_FROM: ${{{{ secrets.EMAIL_FROM }}}}
          EMAIL_TO: ${{{{ secrets.EMAIL_TO }}}}
        run: >-
          uv run --no-sync api-test-pilot notify
          --report {quoted_report}
      - name: Preserve regression outcome
        if: steps.regression.outcome == 'failure'
        run: exit 1

  ai-advice:
    name: Optional GitHub Copilot advice
    needs: regression
    if: >-
      always() &&
      (github.event_name == 'schedule' || github.event_name == 'workflow_dispatch')
    runs-on: ubuntu-latest
    continue-on-error: true
    permissions:
      contents: read
      copilot-requests: write
    steps:
      - name: Check out source
        uses: actions/checkout@v7
      - name: Install uv
        uses: astral-sh/setup-uv@v9.0.0
        with:
          enable-cache: true
      - name: Install Python and locked dependencies
        run: |
          uv python install 3.12
          uv sync --all-extras --locked --no-editable
      - name: Install GitHub Copilot CLI
        continue-on-error: true
        run: |
          set -o pipefail
          mkdir -p ai-reports
          npm install --global @github/copilot@1.0.78 2>&1 | tee ai-reports/copilot-installation.txt
      - name: Generate AI-assisted recommendations
        continue-on-error: true
        env:
          GITHUB_TOKEN: ${{{{ github.token }}}}
        run: |
          set -o pipefail
          mkdir -p ai-reports
          uv run --no-sync api-test-pilot generate --config {quoted_config} --ai 2>&1 |
            tee ai-reports/ai-generation-advice.txt
      - name: Download deterministic regression report
        if: always()
        uses: actions/download-artifact@v8
        with:
          name: api-regression-report
          path: deterministic-artifacts
      - name: Analyze failures with GitHub Copilot
        if: >-
          always() &&
          hashFiles('{downloaded_report}') != '' &&
          (
            (github.event_name == 'workflow_dispatch' && inputs.analyze_failures) ||
            (github.event_name == 'schedule' &&
              vars.API_TEST_PILOT_AI_FAILURE_ANALYSIS == 'true')
          )
        continue-on-error: true
        env:
          GITHUB_TOKEN: ${{{{ github.token }}}}
        run: |
          set -o pipefail
          uv run --no-sync api-test-pilot analyze --report {quoted_downloaded_report} 2>&1 |
            tee ai-reports/ai-failure-analysis.txt
      - name: Upload AI advice and analysis
        if: always()
        uses: actions/upload-artifact@v7
        with:
          name: api-regression-ai-advice
          path: |
            ai-reports/
            deterministic-artifacts/{workflow_reports}/
          if-no-files-found: warn
"""


def write_workflow(
    configuration: ProjectConfiguration,
    destination: Path,
    *,
    config_path: Path,
    overwrite: bool,
) -> None:
    """Write a generated Actions workflow without silent replacement."""
    if destination.exists() and not overwrite:
        raise FileExistsError(f"Workflow already exists: {destination}; use --force to replace it")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        render_workflow(configuration, config_path=config_path),
        encoding="utf-8",
    )
